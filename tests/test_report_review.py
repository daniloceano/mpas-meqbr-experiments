"""Tests for the 2026-11 report review: error x cost dividers, mesh-profile CLI parsing."""

from __future__ import annotations

import importlib.util
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]


def _load(name: str, relative: str):
    spec = importlib.util.spec_from_file_location(name, ROOT / relative)
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


BUILD = _load("build_technical_report", "scripts/06_report/build_technical_report.py")


def _decision(costs, rmses):
    return {"rows": [{"experiment": e, "cost": c, "lidar_rmse_100": r}
                     for e, c, r in zip(["CTL", "EXP01", "EXP02", "EXP03"], costs, rmses)]}


def test_tradeoff_is_relative_to_ctl():
    out = BUILD._tradeoff(_decision([2.0, 2.2, 4.0, 3.0], [2.0, 1.8, 1.9, 1.7]))
    rows = {r["experiment"]: r for r in out["rows"]}
    assert rows["CTL"]["cost_rel"] == pytest.approx(1.0)
    assert rows["CTL"]["rmse_reduction_pct"] == pytest.approx(0.0)
    assert rows["EXP03"]["cost_rel"] == pytest.approx(1.5)
    assert rows["EXP03"]["rmse_reduction_pct"] == pytest.approx(15.0)


def test_tradeoff_divider_is_midpoint_and_partition_bounds_bracket_it():
    out = BUILD._tradeoff(_decision([2.0, 2.2, 4.0, 3.0], [2.0, 1.8, 1.9, 1.7]))
    assert out["x_divider"] == pytest.approx(1.5)          # (1.0 + 2.0) / 2
    assert out["y_divider"] == 0.0
    # 1.5 is itself EXP03's relative cost, so it sits on the divider: the
    # partition bounds are the nearest costs strictly on each side.
    assert out["partition_lo"] == pytest.approx(1.1)
    assert out["partition_hi"] == pytest.approx(2.0)


def test_tradeoff_without_ctl_is_empty():
    assert BUILD._tradeoff({"rows": [{"experiment": "EXP01", "cost": 1.0,
                                      "lidar_rmse_100": 1.0}]}) == {"rows": []}


def test_mesh_profile_parses_generation_command(tmp_path):
    pytest.importorskip("netCDF4")
    pytest.importorskip("yaml")
    profile = _load("export_mesh_spacing_profile",
                    "scripts/06_report/export_mesh_spacing_profile.py")
    domain = tmp_path / "oval_domain.txt"
    domain.write_text(
        "Regional mesh: oval\n"
        "Generated by: create_regional_grid.py -r 5 -l 200 --shape ellipse "
        "-clat -0.459 -clon -44.579 --semi-major 1264 --semi-minor 430 "
        "--orientation 117 --buffer-res 31 --buffer-width 325 "
        "--buffer-profile smoothstep --hfun-dlat 0.05 --hfun-float32 -o oval -p\n")
    args = profile.parse_generation_command(domain)
    assert args["shape"] == "ellipse"
    assert (args["clat"], args["clon"]) == (-0.459, -44.579)
    assert (args["semi_major"], args["semi_minor"], args["orientation"]) == (1264.0, 430.0, 117.0)
    assert (args["r"], args["buffer_res"], args["buffer_width"]) == (5.0, 31.0, 325.0)
    assert args["buffer_profile"] == "smoothstep"
    assert args["relax_pre_cells"] == 2 and args["relax_post_cells"] == 3
    assert args["tr"] == 600.0 and args["buffer"] is None


def test_numeric_values_round_trip(tmp_path, monkeypatch):
    import base64
    import json

    import numpy as np
    pytest.importorskip("matplotlib")
    layers = _load("export_interactive_layers",
                   "scripts/05_exploration/export_interactive_layers.py")
    monkeypatch.setattr(layers, "REPO_ROOT", tmp_path)
    lat = np.array([-1.0, 0.0, 1.0])
    lon = np.array([10.0, 11.0])
    a = np.array([[1.0, 2.0], [3.0, np.nan], [5.0, 6.0]])     # row 0 = south
    b = np.full_like(a, 4.0)
    entries = [{"variable": "v", "experiment": "A", "period": "2021", "_grid": a},
               {"variable": "v", "experiment": "B", "period": "2021", "_grid": b}]
    layers.write_values(entries, lat, lon)
    meta = entries[0]["values"]
    assert "_grid" not in entries[0]
    assert meta["shape"] == [3, 2] and meta["row_order"] == "north_first"
    text = (tmp_path / meta["source"]).read_text()
    payload = json.loads(text.split("] = ", 1)[1].rstrip().rstrip(";"))
    q = np.frombuffer(base64.b64decode(payload), dtype="<u2").reshape(3, 2)
    decoded = np.where(q == meta["nodata"], np.nan, meta["offset"] + q * meta["scale"])
    expected = a[::-1]
    assert np.isnan(decoded[1, 1]) and np.isnan(expected[1, 1])
    ok = np.isfinite(expected)
    assert np.abs(decoded[ok] - expected[ok]).max() <= meta["scale"] / 2 + 1e-12
    # Both layers share one quantisation per variable, so A - B is exact up to it.
    assert entries[1]["values"]["offset"] == meta["offset"]
    assert entries[1]["values"]["scale"] == meta["scale"]


def test_validator_passes_with_warnings_when_videos_are_absent(tmp_path):
    """A clone lacks the unversioned *.mp4: the validator must warn, not fail."""
    import json
    import shutil

    report = ROOT / "results" / "report"
    if not (report / "report_manifest.json").is_file():
        pytest.skip("no built report in this checkout")
    manifest = json.loads((report / "report_manifest.json").read_text(encoding="utf-8"))
    if not any(a.get("optional") for a in manifest["assets"]):
        pytest.skip("report built before optional assets were recorded")
    clone = tmp_path / "report"
    shutil.copytree(report, clone, ignore=shutil.ignore_patterns("*.mp4"))
    validator = _load("validate_technical_report",
                      "scripts/06_report/validate_technical_report.py")
    summary = validator.validate_report(clone)
    optional = {a["bundled_as"] for a in manifest["assets"] if a.get("optional")}
    assert optional and all(a.endswith(".mp4") for a in optional)
    assert summary["warnings"] == [f"optional asset absent: {a}" for a in
                                   [x["bundled_as"] for x in manifest["assets"] if x.get("optional")]]
    # Required assets are still enforced.
    required = next(a for a in manifest["assets"] if not a.get("optional"))
    (clone / required["bundled_as"]).unlink()
    with pytest.raises(AssertionError):
        validator.validate_report(clone)
