#!/usr/bin/env python
"""Export the horizontal-spacing decay of the buffered meshes for the report.

For meqbr_05km_buf (EXP02) and meqbr_05km_oval_meq02a (EXP03), this tabulates
cell spacing against the signed great-circle distance to the boundary of the
area of interest (negative inside), following the convention of
CGFD-USP/MPAS-Research usp-utils (create_regional_grid.py -> plot_resolution):

* spacing  d = sqrt(2 * areaCell_km2 / sqrt(3)), areaCell scaled from the unit
  sphere with R = 6 371 220 m (jigsaw_util.plot_resolution);
* distance from regional_util.polygon_distance_fn over the area-of-interest
  outline rebuilt from the "Generated by:" command line of <mesh>_domain.txt
  (Oval: ellipse with centre, semi-axes and orientation; buf: the polygon of
  the --points-file it names);
* the requested profile from cellwidth_util.buffered_cellwidth and the four
  markers drawn by plot_resolution (area of interest, end of ramp, LBC zone
  starts, mesh edge).

Cells are aggregated in distance bins (n, median, p10, p90), with the
relaxation cells (bdyMaskCell > 0) kept apart. The quasi-uniform CTL mesh has
no buffer, hence no profile.

Run in the ``cgfd-usp-mpas`` conda env (it provides jigsawpy/mpas_tools, which
usp-utils imports at module level). MPAS-Research is only read: bytecode
writing is disabled so no __pycache__ lands in it.

    conda run -n cgfd-usp-mpas python scripts/06_report/export_mesh_spacing_profile.py

Output: results/tables/mesh_spacing_profile.csv
"""

from __future__ import annotations

import argparse
import os
import shlex
import subprocess
import sys
from pathlib import Path

sys.dont_write_bytecode = True  # never write into MPAS-Research

import numpy as np                                         # noqa: E402
import pandas as pd                                        # noqa: E402
import yaml                                                # noqa: E402
from netCDF4 import Dataset                                # noqa: E402

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_MPAS_RESEARCH = "/p1-swell/danilocs/MPAS-Research"
MESHES = ("meqbr_05km_buf", "meqbr_05km_oval_meq02a")
EARTH_RADIUS_M = 6371220.0          # jigsaw_util.plot_resolution
BIN_KM = 10.0
THEORY_STEP_KM = 2.0
# Defaults of create_regional_grid.py (MPAS-Research master@6754c6f).
CLI_DEFAULTS = {"r": 30.0, "l": 200.0, "shape": "circle", "clat": None,
                "clon": None, "semi_major": None, "semi_minor": None,
                "orientation": 0.0, "points_file": None, "buffer": None,
                "tr": 600.0, "buffer_res": None, "buffer_width": None,
                "buffer_decay": None, "buffer_profile": "tanh",
                "relax_pre_cells": 2, "relax_post_cells": 3}
FLAGS = {"-r": "r", "--high": "r", "-l": "l", "--low": "l", "--shape": "shape",
         "-clat": "clat", "--center_latitude": "clat", "-clon": "clon",
         "--center_longitude": "clon", "--semi-major": "semi_major",
         "--semi-minor": "semi_minor", "--orientation": "orientation",
         "--points-file": "points_file", "--buffer": "buffer",
         "-tr": "tr", "--transitionradius": "tr", "--buffer-res": "buffer_res",
         "--outer-resolution": "buffer_res", "--buffer-width": "buffer_width",
         "--buffer-decay": "buffer_decay", "--buffer-growth": "buffer_decay",
         "--buffer-profile": "buffer_profile",
         "--relax-pre-cells": "relax_pre_cells",
         "--relax-post-cells": "relax_post_cells"}
NO_VALUE = {"-p", "--plot", "--preview", "--hfun-float32"}
WITH_VALUE_IGNORED = {"-o", "--output", "--hfun-dlat", "--plot-out",
                      "--polygon-file", "--region-radius"}
# The buf mesh predates the usp-utils commit that versions this code.
GENERATED_BEFORE_CODE = {"meqbr_05km_buf": "e776a835"}


def parse_generation_command(domain_txt: Path) -> dict:
    """Arguments of the ``Generated by:`` line, with the script's defaults."""
    line = next(l for l in domain_txt.read_text().splitlines()
                if l.startswith("Generated by:"))
    tokens = shlex.split(line.split(":", 1)[1])[1:]   # drop the script name
    args = dict(CLI_DEFAULTS)
    i = 0
    while i < len(tokens):
        tok = tokens[i]
        if tok in NO_VALUE:
            i += 1
            continue
        if tok in WITH_VALUE_IGNORED:
            i += 2
            continue
        if tok not in FLAGS:
            raise ValueError(f"{domain_txt}: unknown option {tok!r}")
        key, value = FLAGS[tok], tokens[i + 1]
        args[key] = (value if key in ("shape", "points_file", "buffer_profile")
                     else int(value) if key.startswith("relax")
                     else float(value))
        i += 2
    return args


def geometry(args: dict, rutil, cwutil):
    """Rebuild spec and signed-distance function as create_regional_grid.main."""
    boundary_points = None
    if args["points_file"]:
        loaded = rutil.read_region_spec(args["points_file"])
        args["shape"] = "polygon" if loaded["shape"] == "custom" else loaded["shape"]
        args["clat"] = args["clat"] if args["clat"] is not None else loaded["clat"]
        args["clon"] = args["clon"] if args["clon"] is not None else loaded["clon"]
        boundary_points = loaded["boundary_points"] or None
    clat, clon = args["clat"], args["clon"]
    if args["buffer_res"] is None:
        raise ValueError("mesh has no buffer: no spacing profile to export")
    if args["buffer_width"] is not None:
        width = args["buffer_width"]
    else:
        decay = args["buffer_decay"] if args["buffer_decay"] is not None else 1.10
        width = cwutil.ramp_width_from_growth(args["r"], args["buffer_res"],
                                              decay, args["buffer_profile"])
    spec = cwutil.BufferSpec(
        r=args["r"], r_outer=args["buffer_res"], width=width,
        profile=args["buffer_profile"], n_pre=args["relax_pre_cells"],
        n_post=args["relax_post_cells"], l=args["l"],
        outer_slope=100.0 / args["tr"])
    core_margin = args["buffer"] if args["buffer"] is not None else 0.0
    spacing = min(args["r"], width) / 4.0
    if args["shape"] == "circle":
        raise ValueError("circle domains are not used by these meshes")
    core_points = rutil.region_boundary_polygon(
        args["shape"], clat, clon, region_radius_km=None,
        semi_major_km=args["semi_major"], semi_minor_km=args["semi_minor"],
        orientation_deg=args["orientation"], boundary_points=boundary_points,
        spacing_km=spacing)
    if core_margin > 0.0:
        core_points = rutil.offset_polygon_km(core_points, core_margin, clat, clon)
    dist_fn = rutil.polygon_distance_fn(core_points, clat, clon, spacing_km=spacing)
    return spec, dist_fn


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--mpas-research", default=os.environ.get(
        "MPAS_RESEARCH_ROOT", DEFAULT_MPAS_RESEARCH))
    ap.add_argument("--output", default="results/tables/mesh_spacing_profile.csv")
    args = ap.parse_args()

    root = Path(args.mpas_research)
    sys.path.insert(0, str(root / "usp-utils" / "libs" / "py"))
    import cellwidth_util as cwutil                        # noqa: E402
    import regional_util as rutil                          # noqa: E402

    sha = subprocess.run(["git", "-C", str(root), "rev-parse", "HEAD"],
                         capture_output=True, text=True, check=True).stdout.strip()
    meshes = yaml.safe_load((REPO_ROOT / "config" / "experiments.yaml")
                            .read_text())["meshes"]
    rows = []
    for name in MESHES:
        grid_dir = root / "grids" / name
        grid_path = grid_dir / f"{name}.grid.nc"
        declared = meshes[name]["grid_path"]
        domain_txt = grid_dir / f"{name}_domain.txt"
        cli = parse_generation_command(domain_txt)
        spec, dist_fn = geometry(cli, rutil, cwutil)

        with Dataset(grid_path) as ds:
            lat = np.degrees(ds.variables["latCell"][:])
            lon = np.degrees(ds.variables["lonCell"][:])
            area = np.asarray(ds.variables["areaCell"][:], dtype=float)
            radius = float(getattr(ds, "sphere_radius", 1.0))
            bdy = (np.asarray(ds.variables["bdyMaskCell"][:])
                   if "bdyMaskCell" in ds.variables else np.zeros(lat.size, int))
        lon = np.where(lon > 180.0, lon - 360.0, lon)
        scale = EARTH_RADIUS_M ** 2 if radius == 1.0 else 1.0
        spacing = np.sqrt(2.0 * (area * scale / 1.0e6) / np.sqrt(3.0))
        dist = np.asarray(dist_fn(lon, lat), dtype=float)

        reconstructed = name in GENERATED_BEFORE_CODE
        common = {
            "mesh": name, "source": f"{grid_path}; {domain_txt.name}",
            "mpas_research_sha": sha, "grid_path": declared,
            "theory_reconstructed": reconstructed,
            "note": (f"mesh generated before usp-utils commit "
                     f"{GENERATED_BEFORE_CODE[name]}; requested profile rebuilt "
                     f"from the domain.txt parameters with master@{sha[:8]}"
                     if reconstructed else ""),
        }
        edges = np.arange(np.floor(dist.min() / BIN_KM) * BIN_KM,
                          dist.max() + BIN_KM, BIN_KM)
        for kind, sel in (("interior", bdy == 0), ("relaxation", bdy > 0)):
            idx = np.digitize(dist[sel], edges) - 1
            for k in np.unique(idx):
                v = spacing[sel][idx == k]
                rows.append({**common, "kind": kind,
                             "dist_lo_km": edges[k], "dist_hi_km": edges[k] + BIN_KM,
                             "dist_km": edges[k] + BIN_KM / 2, "n": int(v.size),
                             "median_km": float(np.median(v)),
                             "p10_km": float(np.percentile(v, 10)),
                             "p90_km": float(np.percentile(v, 90))})
        dd = np.arange(dist.min(), dist.max() * 1.02 + THEORY_STEP_KM, THEORY_STEP_KM)
        theory = cwutil.buffered_cellwidth(dd, spec)
        for x, y in zip(dd, theory):
            rows.append({**common, "kind": "theory", "dist_km": float(x),
                         "theory_km": float(y)})
        for label, x in (("area of interest", 0.0), ("end of ramp", spec.width),
                         ("LBC zone starts", spec.cut_offset),
                         ("mesh edge", spec.mesh_offset)):
            rows.append({**common, "kind": "marker", "marker": label,
                         "dist_km": float(x)})
        print(f"[{name}] {lat.size} cells, distance {dist.min():.0f} to "
              f"{dist.max():.0f} km, ramp {spec.width:.1f} km, "
              f"relaxation cells {(bdy > 0).sum()}")

    out = REPO_ROOT / args.output
    columns = ["mesh", "kind", "marker", "dist_lo_km", "dist_hi_km", "dist_km",
               "n", "median_km", "p10_km", "p90_km", "theory_km",
               "theory_reconstructed", "note", "source", "mpas_research_sha",
               "grid_path"]
    frame = pd.DataFrame(rows).reindex(columns=columns)
    frame.to_csv(out, index=False, float_format="%.4f")
    print(f"-> {out.relative_to(REPO_ROOT)} ({len(frame)} rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
